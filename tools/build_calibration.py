"""Builds the judge-practice answer key (calibration/infinity/routines.js) from the calibration
sheet ("WAG Infinity SV Worksheet_calibration routines 2026-27", the source of record), the
routine video folder in Drive, and tools/source/calibration_infinity.json (what the sheet
doesn't hold: skills outside the top 8, a line shown before checking, why each apparatus bonus
is or isn't earned, vault names).

Each sheet tab is one routine: rows 7-14 the top 8 (name, letter, condensed group), column J
notes, L18 the apparatus bonus, N18 the start value. A video is matched to its tab by file name
(BB_3 (limited credit) uses BB_3's video); VT_n videos carry their D-score in the name, "VT_1 (5.1)".

Needs the UCG Google sign-in (~/.ucg/gauth.py; nothing from there is copied or committed), so
it runs locally, not in CI. tests/calibration.test.mjs checks the result against the planner's scoring.

Run: python tools/build_calibration.py   (then commit calibration/infinity/routines.js)
"""
import json
import os
import re
import sys

HERE = os.path.dirname(__file__)
OUT = os.path.join(HERE, "..", "calibration", "infinity", "routines.js")
EVENTS = {"UB": "ub", "BB": "bb", "FX": "fx"}

sys.path.insert(0, os.path.expanduser("~/.ucg"))
from gauth import service  # noqa: E402


def main():
    src = json.load(open(os.path.join(HERE, "source", "calibration_infinity.json"), encoding="utf-8"))
    sheets, drive = service("sheets", "v4"), service("drive", "v3")
    titles = [s["properties"]["title"] for s in sheets.spreadsheets().get(spreadsheetId=src["sheet"]).execute()["sheets"]]
    tabs = sheets.spreadsheets().values().batchGet(spreadsheetId=src["sheet"], ranges=[f"'{t}'!A1:N18" for t in titles]).execute()["valueRanges"]
    files = drive.files().list(
        q=f"'{src['videos']}' in parents and trashed=false", fields="files(id,name,videoMediaMetadata)",
        pageSize=200, supportsAllDrives=True, includeItemsFromAllDrives=True).execute()["files"]
    videos = {os.path.splitext(f["name"])[0]: f for f in files}

    def video(f):
        m = f.get("videoMediaMetadata") or {}
        return {"video": f["id"], "portrait": m.get("height", 0) > m.get("width", 0)}

    routines = []
    for title, tab in zip(titles, tabs):
        rows = tab.get("values", []) + [[]] * 20
        cell = lambda r, c: str(rows[r - 1][c]).strip() if c < len(rows[r - 1]) else ""  # noqa: E731
        skills, notes = [], []
        for r in range(7, 21):
            note = cell(r, 9)
            if note.startswith("Note:") or (note and not cell(r, 2)):
                notes.append(note)
                note = ""
            if 7 <= r <= 14 and cell(r, 2):
                s = {"name": " ".join(cell(r, 2).split()).rstrip("*").strip(), "letter": cell(r, 3), "group": cell(r, 6)}
                if note:
                    s["note"] = note.lstrip("* ").strip()
                skills.append(s)
        bonus = cell(18, 11)
        if bonus not in ("0", "0.0", "0.3"):
            sys.exit(f"{title}: apparatus bonus (L18) is {bonus!r}, not 0 or 0.3")
        if title not in src["bonus_why"]:
            sys.exit(f"{title}: no bonus_why in tools/source/calibration_infinity.json")
        f = videos.get(title.split(" ")[0])
        if not f:
            sys.exit(f"{title}: no video named {title.split(' ')[0]} in the folder")
        routines.append({
            "id": title, "event": EVENTS[title[:2]], **video(f),
            "skills": skills, "extras": src["extras"].get(title, []),
            "eventBonus": bonus == "0.3", "eventBonusWhy": src["bonus_why"][title],
            "sv": float(cell(18, 13)), "notes": notes, "intro": src["intro"].get(title, ""),
        })
    for name, f in sorted(videos.items()):
        m = re.fullmatch(r"(VT_\d+) \(([\d.]+)\)", name)
        if m:
            dv = float(m.group(2))
            routines.append({"id": m.group(1), "event": "vt", **video(f), "dv": dv, "sv": round(10 + dv, 1),
                             "vault": src["vaults"].get(m.group(1)), "intro": src["intro"].get(m.group(1), "")})

    js = (
        "// Generated by tools/build_calibration.py from the calibration sheet, the video folder and\n"
        "// tools/source/calibration_infinity.json. Edit those, not this file.\n"
        f'export const SHEET_URL = "https://docs.google.com/spreadsheets/d/{src["sheet"]}/edit";\n'
        f"export const ROUTINES = {json.dumps(routines, indent=1, ensure_ascii=False)};\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(js)
    print(f"{len(routines)} routines -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
